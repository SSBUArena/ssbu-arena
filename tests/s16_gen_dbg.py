"""S16: writes the debug script of a FOUR-fighter check match.
    python tests/s16_gen_dbg.py <out file> [nofinal=<entry,entry>]
Entries 0..3 = the four fighters of one match (p1 human with the key script of tests\\seq_s15_check.txt, p2 human without input, p3 / p4 CPU players).
The fighters are put 33 apart on the stage (pos) every 280 frames. Entries 1..3 get, from frame 230, every 60 frames one of 21 generated status
requests (15 on the ground: specials, tilts, smashes, dash attack, catch, guard, roll; then 6 in the air), each after a reset (pos + WAIT).
The forced FINAL (flag + term + status) runs one entry after the other: entry 0 at 1625, entry 1 at 2170, 2 at 2710, 3 at 3250 (the original
single-run script did the same for entry 0). 'nofinal=1,3' leaves the Final out for those entries. No game content in this file."""
import sys

X = [-50, -17, 17, 50]
GROUND = ['SPECIAL_N', 'SPECIAL_S', 'SPECIAL_HI', 'SPECIAL_LW', 'ATTACK', 'ATTACK_S3', 'ATTACK_HI3', 'ATTACK_LW3', 'ATTACK_S4_START', 'ATTACK_HI4_START',
          'ATTACK_LW4_START', 'ATTACK_DASH', 'CATCH', 'GUARD_ON', 'ESCAPE_F']
AIR = ['ATTACK_AIR', 'SPECIAL_N', 'SPECIAL_S', 'SPECIAL_HI', 'SPECIAL_LW', 'ATTACK_AIR']
FINAL_AT = [1625, 2170, 2710, 3250]
END = 3800


def main():
    out = sys.argv[1]
    nofinal = set()
    floaters = []
    for a in sys.argv[2:]:
        if a.startswith('float='):
            floaters = [int(x) for x in a[6:].split(',') if x]
        if a.startswith('nofinal='):
            nofinal = set(int(x) for x in a[8:].split(',') if x)
    L = ['# S16 four-fighter check (generated by tests\\s16_gen_dbg.py)']
    for t in (20, 200, 480, 760, 1040, 1320, 1620, 2160, 2700, 3240):
        for e in range(4):
            L.append('at %d pos %d %d 0.1' % (t, e, X[e]))
    K = 'FIGHTER_STATUS_KIND_'
    import os
    global GROUND, AIR
    if os.environ.get('S16_NOLW'):                      # S20t: Pokemon Trainer's Pokemon: SPECIAL_LW swaps the Pokemon and the hash log (frame-line hook) never sees the new one; leave it out
        GROUND = [k for k in GROUND if k != 'SPECIAL_LW']
        AIR = [k for k in AIR if k != 'SPECIAL_LW']
    import os
    for e in ((0, 1, 2, 3) if os.environ.get('S16_BOTH') else (1, 2, 3)):       # S16_BOTH=1: entry 0 is driven by status requests too (key script = idle)
        t = 230 + 7 * e
        for k in GROUND:
            L.append('at %d pos %d %d 0.1' % (t - 3, e, X[e]))
            L.append('at %d status %d %sWAIT' % (t - 2, e, K))
            L.append('at %d status %d %s%s' % (t, e, K, k))
            t += 60
        for k in AIR:
            L.append('at %d pos %d %d 0.1' % (t - 6, e, X[e]))
            L.append('at %d status %d %sWAIT' % (t - 5, e, K))
            L.append('at %d air %d 25' % (t - 3, e))
            L.append('at %d status %d %s%s' % (t, e, K, k))
            t += 60
    for e in floaters:                                  # peach / daisy: float just above the ground, then the side special (must be the AERIAL one)
        for t in (1510, 1600):
            L.append('at %d pos %d %d 0.1' % (t - 6, e, X[e]))
            L.append('at %d status %d %sWAIT' % (t - 5, e, K))
            L.append('at %d air %d 3' % (t - 3, e))
            L.append('at %d status %d FIGHTER_PEACH_STATUS_KIND_UNIQ_FLOAT%s' % (t, e, '_START' if t == 1510 else ''))
            L.append('at %d status %d %sSPECIAL_S' % (t + 30, e, K))
    for e in range(4):
        if e in nofinal:
            continue
        t = FINAL_AT[e]
        L.append('at %d final %d' % (t, e))
        L.append('at %d term %d FIGHTER_STATUS_TRANSITION_TERM_ID_FINAL 1' % (t + 1, e))
        L.append('at %d status %d %sFINAL' % (t + 5, e, K))
    open(out, 'w').write('\n'.join(L) + '\n')
    print('%s: %d lines, run %d fight frames' % (out, len(L), END))


main()
