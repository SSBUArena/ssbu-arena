"""The moveset file as input for writing a fighter's source by hand.

    python -I moveset.py listing <main fighter .pac> <costume .pac> <out .txt>
    python -I moveset.py draft   <main fighter .pac> <costume .pac> <out folder> <fighter name>
    python -I moveset.py extra   <main fighter .pac> <costume .pac> <out .txt> [item parameter .pac ...]

extra: the scripts the listing does not reach: loops running beside the actions, the interrupt list, the articles'
scripts and the scripts inside the item parameter archives (layouts inferred from the package).

listing: attributes (with the native parameter of the same meaning where there is one), hurt boxes, the model-switch
table, then every sub-action with its four scripts walked (subroutines followed, frames from the timers).
draft: a FIRST DRAFT of native move scripts (the form of the fighter sources: ACMD(<name>, game_<motion>) with
frame / wait / ATTACK / CATCH / ATTACK_ABS) for normals, tilts, smashes, aerials, grabs and throws. Generated,
never compiled, never run: for a person to review. The costume archive gives the bone names.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from brawl import arc, psa_listing as pl                    # noqa: E402
from brawl.convert_anim import load_model                   # noqa: E402
from brawl.convert_model import RENAME as BONE_MAP          # noqa: E402
from brawl.psa import Psa                                   # noqa: E402

DRAFT = {   # sub-action name of the package -> native script name
    'Attack11': 'attack11', 'Attack12': 'attack12', 'Attack13': 'attack13', 'AttackDash': 'attackdash',
    'AttackS3S': 'attacks3', 'AttackHi3': 'attackhi3', 'AttackLw3': 'attacklw3', 'AttackS4S': 'attacks4',
    'AttackHi4': 'attackhi4', 'AttackLw4': 'attacklw4', 'AttackAirN': 'attackairn', 'AttackAirF': 'attackairf',
    'AttackAirB': 'attackairb', 'AttackAirHi': 'attackairhi', 'AttackAirLw': 'attackairlw', 'Catch': 'catch',
    'CatchDash': 'catchdash', 'CatchTurn': 'catchturn', 'CatchAttack': 'catchattack', 'ThrowF': 'throwf',
    'ThrowB': 'throwb', 'ThrowHi': 'throwhi', 'ThrowLw': 'throwlw',
}
ATTR = {'slash': 'cutup', 'fire': 'fire', 'electric': 'elec', 'ice': 'ice', 'normal': 'normal'}


def open_psa(pac):
    a = arc.load(pac)
    for e in a.entries:
        if e.type == 1 and e.size > 0x1000:
            return Psa(e.data)
    raise SystemExit('no moveset file in ' + pac)


def namers(model):
    names = {b.index: b.name for b in model.bones}
    native = {}
    for nat, pkg in BONE_MAP:
        if nat not in ('Rot', 'Face', 'ClavicleC', 'LegC', 'Hilt'):      # secondary names of the same bone
            native.setdefault(pkg, nat)

    def listing(i):
        n = names.get(i, '?')
        return '%d(%s%s)' % (i, n, ' -> ' + native[n] if n in native else '')

    def source(i):
        n = names.get(i)
        if i == 0 or n is None:
            return 'top'
        return (native.get(n) or n).lower()
    return listing, source


def listing(args):
    p, model = open_psa(args[0]), load_model(args[1])
    bone, _src = namers(model)
    out = []
    w = out.append
    w('MOVESET LISTING (generated by fighter_sdk\\tools\\brawl\\moveset.py; package-derived: local only)')
    w('frames: the timers of the scripts ("frame N" = N frames elapsed; a command at frame N acts on game frame N + 1);')
    w('names with "?" are guesses; both branches of every "if" are listed; subroutines are followed (indented).')
    w('')
    w('ATTRIBUTES  (offset, name, value -> native parameter)')
    att = {name: val for _o, name, val, _n, _t in pl.attributes(p)}
    g = att.get('gravity') or 0.0
    for off, name, val, native, note in pl.attributes(p):
        conv = ''
        if native in ('jump_y', 'mini_jump_y', 'jump_aerial_y') and g:
            v0 = val if native != 'jump_aerial_y' else val * att['jump vertical initial velocity']
            # height of a jump with initial velocity v0 losing g per frame
            conv = '  = height %.2f (v^2 / 2g + v / 2)' % (v0 * v0 / (2 * g) + v0 / 2)
        w('  %#05x  %-38s %10.4f  -> %-28s %s%s' % (off, name, val, native or '-', note, conv))
    w('')
    w('HURT BOXES  (offsets in the bone\'s own axes; the native extra bone of the same name has the same axes)')
    for h in pl.hurtboxes(p):
        w('  bone %-28s offset (%.2f %.2f %.2f) stretch (%.2f %.2f %.2f) radius %.2f zone %d flags %#x' % (
            bone(h['bone']), *h['offset'], *h['stretch'], h['radius'], h['zone'], h['flags']))
    w('')
    switches, defaults = pl.model_switches(p)
    w('MODEL SWITCHES  (command "model switch (switch, group)": the group\'s bones show their meshes, the other '
      'groups\' bones hide theirs)')
    for s, groups in enumerate(switches):
        w('  switch %d (default group %d): %s' % (s, defaults.get(s, 0), '; '.join(
            'group %d = [%s]' % (gi, ', '.join(bone(b) for b in grp)) for gi, grp in enumerate(groups))))
    w('')
    ent, ext = p.header[9], p.header[10]
    n_act = (ext - ent) // 4 if ext > ent else 0
    w('FIGHTER-SPECIFIC ACTIONS  (the state machine part of the file: %d actions, numbered from 0x112: neutral, '
      'side, up, down special, final, then the fighter\'s extra ones; "entry" runs when the action starts)' % n_act)
    for i in range(n_act):
        for label, base in (('entry', ent), ('exit', ext)):
            lines = list(pl.walk(p, p.u32(base + i * 4)))
            if lines:
                w('  ACTION %#x [%s]' % (0x112 + i, label))
                for frame, depth, code, params in lines:
                    w('    %6.1f %s%s' % (frame, '    ' * depth, pl.describe(p, code, params, bone)))
    w('')
    for s in p.subactions:
        w('SUB-ACTION %#05x  %-24s blend %d flags %#x' % (s['index'], s['name'] or '(no animation)', s['blend'],
                                                         s['flags']))
        for nm in ('main', 'gfx', 'sfx', 'other'):
            lines = list(pl.walk(p, s['scripts'][nm]))
            if not lines:
                continue
            w('  [%s]' % nm)
            for frame, depth, code, params in lines:
                w('    %6.1f %s%s' % (frame, '    ' * depth, pl.describe(p, code, params, bone)))
    with open(args[2], 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('%d lines written to %s (%d sub-actions)' % (len(out), args[2], len(p.subactions)))


def _script_lines(p, off, bone, w, indent='    '):
    n = 0
    for frame, depth, code, params in pl.walk(p, off):
        s = pl.describe(p, code, params, bone)
        if s != 'nop':
            w('%s%6.1f %s%s' % (indent, frame, '    ' * depth, s))
            n += 1
    return n


def _is_script(p, off):
    if not off or off + 8 > p.data_size or off % 4:
        return False
    code = p.u32(off)
    mod, n, unk, po = code >> 24, (code >> 8) & 0xFF, code & 0xFF, p.u32(off + 4)
    if code == 0 or mod >= 0x70 or unk > 1:
        return False
    if n == 0:
        return po == 0 and code in pl.EVENTS
    return (off + 4) in p.relocs and n <= 0x20 and po + n * 8 <= p.data_size


def extra(args):
    """The scripts the sub-action listing does not reach: the loops that run beside an action ("concurrent"), the
    interrupt list (what the fighter may start from which state), the articles' scripts and, for every item
    parameter archive given, the item's scripts. Layouts of the article entries and of the item files are INFERRED
    from this package (pointer words that lead to a list of valid commands)."""
    p, model = open_psa(args[0]), load_model(args[1])
    bone, _src = namers(model)
    plain = lambda i: 'bone%d' % i                                                      # noqa: E731
    out = []
    w = out.append
    w('MOVESET EXTRA SCRIPTS (generated by moveset.py extra; package-derived: local only; layouts inferred)')
    w('')
    # 1. concurrent loops: every pointer argument of the "concurrent" commands in any script of the file
    starts = [s['scripts'][nm] for s in p.subactions for nm in ('main', 'gfx', 'sfx', 'other')]
    ent, ext = p.header[9], p.header[10]
    for i in range((ext - ent) // 4 if ext > ent else 0):
        starts += [p.u32(ent + i * 4), p.u32(ext + i * 4)]
    loops, todo = {}, list(starts)
    while todo:
        for _f, _d, code, params in pl.walk(p, todo.pop()):
            if code in (0x0D000200, 0x0D070200, 0x0D050200) and len(params) > 1 and params[1][0] == 2:
                if params[1][1] not in loops:
                    loops[params[1][1]] = Psa.val(params[0])
                    todo.append(params[1][1])
    # the always-running loops named in the data table (id, ?, script) after the fixed header words
    base = p.sections['data']
    for k in range(31, 60):
        o = base + k * 4
        if o in p.relocs and _is_script(p, p.u32(o)) and p.u32(o) not in loops and p.u32(o - 8) < 32:
            loops[p.u32(o)] = p.u32(o - 8)
    w('CONCURRENT LOOPS  (run every frame beside the action that starts them; id = the slot they occupy)')
    for off in sorted(loops):
        w('  LOOP @%#x (slot %s)' % (off, loops[off]))
        _script_lines(p, off, bone, w)
    w('')
    # 2. the interrupt list: data-table word 22 -> {0, 0, script}
    lst = p.header[22]
    if lst and (lst + 8) in p.relocs:
        w('INTERRUPT LIST  (which statuses / actions the fighter may start, by interrupt group, with requirements)')
        _script_lines(p, p.u32(lst + 8), bone, w)
        w('')
    # 3. articles: the pointer words after the fixed header that lead to entries {id, group, bone, ... lists}
    w('ARTICLES  ("generate article N" seems to take the entries below counted from 0 after the first one; '
      'entry words: id, group, bone; then pointers to script lists)')
    entries = [p.u32(base + k * 4) for k in range(31, 44) if (base + k * 4) in p.relocs]
    entries = [e for e in entries if p.u32(e) < 16 and (e + 12) in p.relocs or (e + 16) in p.relocs]
    for n, e in enumerate(entries):
        w('  ARTICLE ENTRY %d @%#x: id %d, group %d, bone %s' % (
            n, e, p.u32(e), p.u32(e + 4) - (1 << 32) if p.u32(e + 4) >> 31 else p.u32(e + 4),
            bone(p.u32(e + 8)) if p.u32(e + 8) < 200 else '-'))
        seen = set()
        for o in range(e + 12, e + 0x3C, 4):
            if o not in p.relocs:
                continue
            t = p.u32(o)
            cands = [t]
            if t in p.relocs:                                   # a list of pointers
                cands = []
                q = t
                while q in p.relocs and len(cands) < 16:
                    cands.append(p.u32(q))
                    q += 4
            for c in cands:
                c2 = p.u32(c) if (c in p.relocs and not _is_script(p, c)) else c
                for s in (c, c2):
                    if s not in seen and _is_script(p, s):
                        seen.add(s)
                        w('    script @%#x (entry word +%#x)' % (s, o - e))
                        _script_lines(p, s, plain, w, '      ')
    w('')
    # 4. items
    for path in args[3:]:
        a = arc.load(path)
        ip = [Psa(e.data) for e in a.entries if e.type == 1][0]
        w('ITEM FILE %s' % os.path.basename(path))
        top = ip.sections.get('animParam')
        if top is None:
            w('  (no animParam section: not walked)')
            continue
        seen = set()
        for slot in range(top - 0xE4, top, 4):
            if slot not in ip.relocs:
                continue
            off = ip.u32(slot)
            if top - 0xE4 <= off < top and off in ip.relocs:
                off = ip.u32(off)
            if off in seen or not _is_script(ip, off):
                continue
            seen.add(off)
            w('  script @%#x (table slot %#x)' % (off, slot))
            _script_lines(ip, off, plain, w)
        w('')
    with open(args[2], 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('%d lines written to %s (%d loops, %d article entries)' % (len(out), args[2], len(loops), len(entries)))


def ff(x):
    s = '%.4g' % x
    return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'


def draft(args):
    p, model = open_psa(args[0]), load_model(args[1])
    out_dir, fighter = args[2], args[3]
    _lst, bone = namers(model)
    os.makedirs(out_dir, exist_ok=True)
    L = []
    w = L.append
    w('// %s: move scripts "game_*" - GENERATED DRAFT, NEVER COMPILED, NEVER RUN.' % fighter)
    w('// Made by fighter_sdk/tools/brawl/moveset.py from the package\'s moveset file (main script of each sub-action,')
    w('// subroutines inlined, BOTH branches of every condition kept with the condition as a comment).')
    w('// To review by a person before it replaces anything in src/%s/acmd/game.cpp:' % fighter)
    w('//  - frame numbers: package timer + 1 (a command after "N frames elapsed" acts on frame N + 1): convention unverified')
    w('//  - the arguments of ATTACK after the SDI multiplier are DEFAULTS copied from the form of a native sword')
    w('//    fighter\'s scripts, except shield damage, trip chance, rehit and the element; sound level / region are guesses')
    w('//  - a value that is a variable in the package is written as 0 with a comment naming the variable')
    w('//  - everything that is not a timer, hitbox, grab box, throw or interrupt is a comment line')
    w('#include "fighter_sdk.h"')
    w('')
    n_scripts = n_attack = 0
    best = {}                      # a name can occur twice in the table: the one with the longer main script
    for s in p.subactions:
        if s['name'] in DRAFT:
            n = len(p.script(s['scripts']['main']))
            if s['name'] not in best or n > best[s['name']][0]:
                best[s['name']] = (n, s['index'])
    for s in p.subactions:
        if s['name'] not in DRAFT or best[s['name']][1] != s['index']:
            continue
        n_scripts += 1
        w('ACMD(%s, game_%s) {    // package sub-action %#x %s' % (fighter, DRAFT[s['name']], s['index'], s['name']))
        pending = []

        def flush():
            if pending:
                w('    if (is_excute(agent)) {')
                for ln in pending:
                    w('        ' + ln)
                w('    }')
                del pending[:]
        for frame, depth, code, params in pl.walk(p, s['scripts']['main']):
            v = [Psa.val(x) for x in params]
            raw = [x[1] for x in params]
            var = [pl.fmt_var(x[1]) if x[0] == 5 else None for x in params]

            def num(i, as_float=True):
                if var[i]:
                    return ('0.0f' if as_float else '0') + ' /* %s */' % var[i]
                return ff(v[i]) if as_float else str(int(v[i]))
            if code == 0x00020100 and params:
                flush()
                w('    frame(agent, %s);' % ('%g' % (v[0] + 1)))
            elif code == 0x00010100 and params:
                flush()
                w('    wait(agent, %s);' % ('%g' % v[0]))
            elif code in (0x06000D00, 0x06150F00) and len(params) >= 13:
                n_attack += 1
                el = pl.ELEMENTS.get(raw[12] & 0x1F, 'normal')
                sword = bone(raw[0] >> 16).startswith('sword')
                rehit = num(13, False) if code == 0x06150F00 and len(params) > 13 else '0'
                pending.append(
                    'ATTACK(agent, %d, 0, hash40("%s"), %s, %s, %d, %d, %d, %s, %s, %s, %s, NIL, NIL, NIL, %s, %s, '
                    'ATTACK_SETOFF_KIND_ON, ATTACK_LR_CHECK_F, false, %d, %s, %s, false, false, false, false, true, '
                    'COLLISION_SITUATION_MASK_GA, COLLISION_CATEGORY_MASK_ALL, COLLISION_PART_MASK_ALL, false, '
                    'hash40("collision_attr_%s"), ATTACK_SOUND_LEVEL_M, COLLISION_SOUND_ATTR_%s, ATTACK_REGION_%s);'
                    '%s' % (raw[0] & 0xFFFF, bone(raw[0] >> 16), num(1), num(2, False), raw[3] & 0xFFFF,
                            raw[3] >> 16, raw[4] & 0xFFFF, num(5), num(6), num(7), num(8), num(10), num(11),
                            raw[4] >> 16, num(9), rehit, ATTR.get(el, 'normal'),
                            'CUTUP' if el == 'slash' else 'PUNCH', 'SWORD' if sword else 'NONE',
                            '' if el in ATTR else '   // package element: %s' % el))
            elif code == 0x06040000:
                pending.append('AttackModule::clear_all(boma);')
            elif code in (0x060A0800, 0x060A0A00) and len(params) >= 6:
                pending.append('CATCH(agent, %d, hash40("%s"), %s, %s, %s, %s, NIL, NIL, NIL, '
                               'FIGHTER_STATUS_KIND_CAPTURE_PULLED, COLLISION_SITUATION_MASK_GA);' % (
                                   int(v[0]), bone(raw[1]), num(2), num(3), num(4), num(5)))
            elif code == 0x060D0000:
                pending.append('grab(agent, MA_MSC_CMD_GRAB_CLEAR_ALL);   // form to check against a native script')
            elif code == 0x060E1100 and len(params) >= 7:
                kind = 'THROW' if int(v[0]) == 0 else 'CATCH'
                pending.append('ATTACK_ABS(agent, FIGHTER_ATTACK_ABSOLUTE_KIND_%s, 0, %s, %s, %s, %s, %s, 0.0f, 1.0f, '
                               'ATTACK_LR_CHECK_F, 0.0f, true, hash40("collision_attr_normal"), ATTACK_SOUND_LEVEL_S, '
                               'COLLISION_SOUND_ATTR_NONE, ATTACK_REGION_THROW);' % (
                                   kind, num(2), num(3, False), num(4, False), num(5, False), num(6, False)))
            elif code == 0x060F0500:
                pending.append('// THROW RELEASE here: in a native script ATK_HIT_ABS(agent, '
                               'FIGHTER_ATTACK_ABSOLUTE_KIND_THROW, hash40("throw"), <target object, group, no>) '
                               '- package parameters: %s' % ', '.join(pl.fmt_param(p, x) for x in params))
            elif code == 0x64000000:
                pending.append('// package: the move can be interrupted from this frame (native: the motion\'s '
                               'cancel frame is a field of the motion list, not a script line)')
            elif code in (0x00020000,):
                pass
            else:
                pending.append('// %s%s' % ('    ' * depth, pl.describe(p, code, params, bone)))
        flush()
        w('}')
        w('')
    path = os.path.join(out_dir, 'game_draft.cpp')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print('%d scripts, %d ATTACK lines written to %s' % (n_scripts, n_attack, path))


if __name__ == '__main__':
    if len(sys.argv) == 5 and sys.argv[1] == 'listing':
        listing(sys.argv[2:])
    elif len(sys.argv) == 6 and sys.argv[1] == 'draft':
        draft(sys.argv[2:])
    elif len(sys.argv) >= 5 and sys.argv[1] == 'extra':
        extra(sys.argv[2:])
    else:
        print(__doc__)
